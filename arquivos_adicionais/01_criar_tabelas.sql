-- UrbanLink Flow | PostgreSQL / Supabase
-- Execute apenas em um banco NOVO, apos selecionar o projeto correto.
-- Nao apaga tabelas nem dados existentes. Nao e uma migration de banco em uso.
-- As aspas preservam os nomes definidos no ORM Sequelize.

BEGIN;

CREATE TABLE IF NOT EXISTS public."Usuarios" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    cpf_cnpj VARCHAR(255) DEFAULT '',
    cidade VARCHAR(255) DEFAULT '',
    veiculo_preferencia VARCHAR(255) DEFAULT 'Carro',
    tipo_conta VARCHAR(255) DEFAULT 'pessoal',
    perfil VARCHAR(255) NOT NULL DEFAULT 'operador',
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Usuarios_perfil_check" CHECK (perfil IN ('operador', 'administrador'))
);

CREATE TABLE IF NOT EXISTS public."Produtos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    nome VARCHAR(255) NOT NULL,
    categoria VARCHAR(255) NOT NULL DEFAULT 'Geral',
    quantidade INTEGER NOT NULL DEFAULT 0,
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Produtos_quantidade_check" CHECK (quantidade >= 0)
);

CREATE TABLE IF NOT EXISTS public."Veiculos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(255) NOT NULL UNIQUE,
    modelo VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL DEFAULT 'Carro',
    capacidade_kg INTEGER NOT NULL DEFAULT 100,
    status VARCHAR(255) NOT NULL DEFAULT 'disponivel',
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Veiculos_capacidade_kg_check" CHECK (capacidade_kg > 0)
);

-- Nome e valores alinhados ao ENUM definido em src/models/Entrega.js.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'enum_Entregas_status' AND n.nspname = 'public'
    ) THEN
        CREATE TYPE public."enum_Entregas_status"
            AS ENUM ('pendente', 'em_transito', 'entregue', 'concluido');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public."Entregas" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_rastreio VARCHAR(255) NOT NULL UNIQUE,
    destino VARCHAR(255) NOT NULL,
    peso_kg INTEGER NOT NULL DEFAULT 1,
    status public."enum_Entregas_status" DEFAULT 'pendente',
    produto_id INTEGER NULL,
    veiculo_id INTEGER NULL,
    usuario_id INTEGER NULL,
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "Entregas_peso_kg_check" CHECK (peso_kg > 0),
    CONSTRAINT "Entregas_produto_id_fkey" FOREIGN KEY (produto_id)
        REFERENCES public."Produtos" (id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT "Entregas_veiculo_id_fkey" FOREIGN KEY (veiculo_id)
        REFERENCES public."Veiculos" (id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT "Entregas_usuario_id_fkey" FOREIGN KEY (usuario_id)
        REFERENCES public."Usuarios" (id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_entregas_produto ON public."Entregas" (produto_id);
CREATE INDEX IF NOT EXISTS idx_entregas_veiculo ON public."Entregas" (veiculo_id);
CREATE INDEX IF NOT EXISTS idx_entregas_usuario ON public."Entregas" (usuario_id);

-- Defesa em profundidade: sem policies publicas e sem grants para anon/authenticated.
-- O backend se conecta ao PostgreSQL diretamente no servidor, nunca pelo navegador.
ALTER TABLE public."Usuarios" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Produtos" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Veiculos" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Entregas" ENABLE ROW LEVEL SECURITY;

COMMIT;

-- IMPORTANTE: no campo legado "peso_kg", a aplicacao guarda a quantidade
-- de unidades solicitadas, nao o peso fisico da mercadoria.
